/* ---------------------------------------------------------------------- *
 * Hilfsfunktionen
 *
 * Alle Ausgaben laufen über diese Filter. Einträge mit 'do-not-publish'
 * erscheinen dadurch an keiner Stelle der Website, ohne dass jede Seite das
 * einzeln prüfen müsste.
 * ---------------------------------------------------------------------- */

/** Darf überhaupt ausgegeben werden? */
export const darfErscheinen = (e: { status: ReferenzStatus }) => e.status !== 'do-not-publish';

/** Projektreferenzen, die auf der Website erscheinen dürfen. */
export const sichtbareReferenzen = PROJEKTREFERENZEN.filter(darfErscheinen);

/** Referenzschreiben, die auf der Website erscheinen dürfen. */
export const sichtbareSchreiben = REFERENZSCHREIBEN.filter(darfErscheinen);

/** Kundenlogos, die auf der Website erscheinen dürfen. */
export const sichtbareLogos = KUNDENLOGOS.filter(darfErscheinen);

/**
 * Referenzen, die als gesicherte aktuelle Projekte gelten.
 *
 * Verlangt beides: inhaltliche Prüfung (`verified`) und Textfreigabe. Solange
 * beides nicht vorliegt, ist die Liste leer — das ist beabsichtigt und
 * verhindert, dass ungeprüfte Angaben an prominenter Stelle erscheinen.
 */
export const gesicherteAktuelleReferenzen = PROJEKTREFERENZEN.filter(
  (r) =>
    r.referenzTyp !== 'historisch' &&
    r.status === 'verified' &&
    r.textFreigabe === 'freigegeben',
);

/** Ist die Referenz ein abgeschlossenes Projekt der Unternehmenshistorie? */
export const istHistorisch = (r: Projektreferenz) => r.referenzTyp === 'historisch';

/**
 * Sortierung der Projektübersicht: erst die nicht-historischen Referenzen,
 * dann die historischen. Innerhalb der Gruppen bleibt die bisherige
 * Reihenfolge erhalten.
 */
export const referenzenNachTyp = [
  ...sichtbareReferenzen.filter((r) => !istHistorisch(r)),
  ...sichtbareReferenzen.filter(istHistorisch),
];

/** Slugs, die im Leistungsfinder als Ergebnis erscheinen dürfen. */
export const freigegebeneSlugs = new Set(
  PROJEKTREFERENZEN.filter(
    (r) => r.slug && r.status !== 'do-not-publish' && r.textFreigabe !== 'abgelehnt',
  ).map((r) => r.slug as string),
);
