/**
 * Zentrale Referenzverwaltung.
 *
 * Diese Datei ist die einzige Quelle für Projektreferenzen, Kundenlogos und
 * Referenzschreiben. Die Projektübersicht, die Logo-Laufschrift und das
 * Referenzband lesen daraus; im Markup steht nichts mehr doppelt.
 *
 * Zwei Dinge werden hier bewusst getrennt geführt:
 *
 *  - `verifiziert` sagt, ob die inhaltliche Angabe geprüft wurde.
 *  - `status`, `logoFreigabe` und `textFreigabe` sagen, ob veröffentlicht
 *    werden darf.
 *
 * Beides ist nicht dasselbe: Eine Angabe kann inhaltlich stimmen und trotzdem
 * ohne Freigabe des Kunden nicht auf die Website gehören. Alle Bestandsdaten
 * stehen deshalb zunächst auf `pending` und `offen` — sie stammen aus der
 * bisherigen Unternehmenswebsite, eine markenrechtliche oder vertragliche
 * Freigabe ist damit nicht belegt.
 *
 * FREIGABEN PFLEGEN: ausschließlich in dieser Datei, in den Feldern `status`,
 * `logoFreigabe`, `textFreigabe`, `schreibenFreigabe` und `verifiziert`.
 * Offene Punkte sind in LIVEGANG_CHECKLISTE.md aufgeführt.
 *
 * Einträge mit `status: 'do-not-publish'` werden von den Hilfsfunktionen am
 * Ende der Datei herausgefiltert und erscheinen nirgends auf der Website. Die
 * Datensätze und Bilddateien bleiben erhalten — eine fehlende Freigabe ist
 * kein Grund, Material zu löschen.
 */

/** Darf der Eintrag veröffentlicht werden? */
export type ReferenzStatus = 'verified' | 'pending' | 'do-not-publish';

/** Freigabe eines einzelnen Bestandteils. */
export type Freigabe = 'freigegeben' | 'offen' | 'abgelehnt' | 'entfaellt';

/** Aktuelle Tätigkeit oder abgeschlossenes Projekt der Unternehmenshistorie? */
export type ReferenzTyp = 'aktuell' | 'historisch' | 'unbestimmt';

/**
 * Rolle von ELCON im Projekt.
 *
 * 'unklar' ist der Regelfall im Bestand: Aus den übernommenen Texten geht
 * häufig nicht hervor, ob ELCON Hauptauftragnehmer, Nachunternehmer oder
 * ausführender Partner war. Wo die Detailseite einen Generalunternehmer
 * nennt, der nicht ELCON ist, steht 'nachunternehmer'.
 */
export type Rolle =
  | 'generalunternehmer'
  | 'technischer-gu'
  | 'nachunternehmer'
  | 'ausfuehrend'
  | 'planung'
  | 'unklar';

/** Grobe geografische Zuordnung, für Filterung und Gruppierung. */
export type Region = 'deutschland' | 'europa' | 'gus' | 'ostsee' | 'afrika' | 'unbekannt';

/** Darstellung der Kachel in der Projektübersicht. */
export type Darstellung = 'logo' | 'logo-klein' | 'logo-gross' | 'logo-doppelt' | 'text';

export interface ReferenzLogo {
  /** Dateiname in src/assets/logos. */
  datei: string;
  alt: string;
  altEn: string;
}

export interface Projektreferenz {
  id: string;
  /** Auftraggeber oder beteiligte Organisation, soweit belegt. */
  organisation: string | null;
  projektname: string;
  projektnameEn: string;
  land: string | null;
  landEn: string | null;
  ort: string | null;
  /** Ausführungszeitraum, soweit belegt. null = nicht dokumentiert. */
  zeitraum: string | null;
  referenzTyp: ReferenzTyp;
  region: Region;
  rolle: Rolle;
  /** Gewerk für die bestehende Filterung der Übersicht. */
  kategorie: string;
  metaZeile: string;
  metaZeileEn: string;
  kurzText: string;
  kurzTextEn: string;
  darstellung: Darstellung;
  textPlatte: string | null;
  textPlatteEn: string | null;
  logos: ReferenzLogo[];
  /** Slug der Detailseite in src/data/projekte.ts, falls vorhanden. */
  slug: string | null;
  status: ReferenzStatus;
  verifiziert: boolean;
  logoFreigabe: Freigabe;
  textFreigabe: Freigabe;
  hervorgehoben: boolean;
  /** Woher die Angaben stammen. */
  quelle: string | null;
}

